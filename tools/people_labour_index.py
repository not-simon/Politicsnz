#!/usr/bin/env python3
"""Build parties/labour/people/README.md index from each person.json."""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
P = ROOT / 'parties' / 'labour' / 'people'
PARTY = {'labour': 'Labour', 'nz-first': 'NZ First', 'te-pati-maori': 'Te Pāti Māori', 'independent': 'Independent',
         'opportunity': 'The Opportunity Party', 'green': 'Green'}
STATUS = {'current-mp-standing-2026': 'MP, standing 2026', 'current-mp-retiring': 'MP, retiring', 'current-mp': 'MP',
          'candidate-2026': '2026 candidate', 'former-mp': 'Former MP', 'deceased': 'Deceased', 'party-official': 'Party official'}
people = [json.loads((d / 'person.json').read_text()) for d in sorted(P.iterdir()) if (d / 'person.json').exists()]

def short_roles(p, n=2):
    out = []
    for r in p.get('roles') or []:
        if r.startswith('Labour shadow cabinet'):
            r = re.sub(r' \(as of 11 Mar 2026\)', '', r)
            r = r.split(':')[0] + ': ' + '; '.join(r.split(': ', 1)[1].split('; ')[:3])
        out.append(r)
        if len(out) >= n: break
    return '<br>'.join(out).replace('|', '/')

def row(p, mode):
    s = p['slug']
    img = f'<img src="{s}/photo.jpg" width="48" alt="">' if (P / s / 'photo.jpg').exists() else ''
    name = f"[{p['name']}]({s}/)"
    st = STATUS.get(p['status'], p['status'])
    if p.get('party', 'labour') != 'labour':
        st += f" ({PARTY.get(p['party'], p['party'])})"
    if p.get('status_detail') and mode == 'former':
        pass
    elec = ', '.join(p.get('electorates') or []) or ('List' if p.get('parliaments') else '—')
    e26 = p.get('electorate_2026') or ''
    rk = p.get('list_rank_2026')
    cand = (e26 or ('List only' if rk else '')) + (f' · #{rk}' if rk else (' · electorate only' if e26 else ''))
    parls = ', '.join(str(x) for x in p.get('parliaments') or [])
    if mode == 'current':
        return f"| {img} | {name} | {st} | {elec} | {cand or '—'} | {short_roles(p)} |"
    if mode == 'cand':
        return f"| {rk or '—'} | {img} | {name} | {e26 or 'List only'} | {'Former MP (' + parls + ')' if parls else 'New'} | {(p.get('questionnaire_2026') or {}).get('Before politics', '') or ''} |"
    return f"| {img} | {name} | {st} | {elec} | {parls} | {cand or '—'} | {short_roles(p)} |"

cur = [p for p in people if p['status'].startswith('current')]
cand = [p for p in people if p['status'] == 'candidate-2026']
former = [p for p in people if p['status'] in ('former-mp', 'deceased', 'party-official')]
cur.sort(key=lambda p: (p.get('list_rank_2026') or 999, p['name']))
cand.sort(key=lambda p: (p.get('list_rank_2026') or 999, p.get('electorate_2026') or '', p['name']))
former.sort(key=lambda p: p['name'].split()[-1])
L = ['# Labour people', '',
     'Profiles of everyone who sat as a Labour MP in the 50th–54th Parliaments (2011–2026), and of every Labour candidate at the 7 November 2026 election. MPs who later left Labour stay in this folder, and their party history records the move. Status is as of 23 October 2026; the 54th Parliament was dissolved on 1 October 2026.', '',
     f'**{len(people)} profiles:** {len(cur)} MPs at dissolution (34 Labour MPs plus Shane Jones, now an NZ First MP), {len(cand)} 2026 candidates who are not sitting MPs, and {len(former)} former or deceased MPs. Each folder holds `README.md`, `person.json` (see [docs/SCHEMA.md](../../../docs/SCHEMA.md)) and `photo.jpg`, with the photo source, credit and licence recorded in `person.json`.', '',
     'List ranks and 2026 electorates come from Labour candidate data published on [policy.nz](https://policy.nz/2026/party-vote/parties/labour-party). Opposition portfolios are taken from [Shadow Cabinet of Chris Hipkins](https://en.wikipedia.org/wiki/Shadow_Cabinet_of_Chris_Hipkins) as of 11 March 2026.', '',
     '## Current MPs (54th Parliament, at dissolution)', '',
     '| | Name | Status | Electorate(s) held | 2026 candidacy | Roles |', '|---|---|---|---|---|---|']
L += [row(p, 'current') for p in cur]
L += ['', '## 2026 candidates (not sitting MPs), by list rank', '',
      'Candidates without a rank are standing in an electorate only. Kerrin Leoni (Tāmaki Makaurau, #43) resigned as a Labour candidate on 23 October 2026. Her name stays on the ballot, but without Labour\'s endorsement (see [her profile](kerrin-leoni/)).', '',
      '| List # | | Name | 2026 electorate | Background | Occupation (policy.nz) |', '|---|---|---|---|---|---|']
L += [row(p, 'cand') for p in cand]
L += ['', '## Former MPs (served 2011–2026)', '',
      '| | Name | Status | Electorate(s) held | Parliaments | 2026 candidacy | Roles |', '|---|---|---|---|---|---|---|']
L += [row(p, 'former') for p in former]
L += ['', '_Generated by `tools/people_labour_index.py` from each `person.json`; profiles built by `tools/people_labour_build.py` from Wikipedia and the cited sources, plus hand-written notes in `tools/people_labour_notes/`._', '']
(P / 'README.md').write_text('\n'.join(L))
print(len(cur), len(cand), len(former))
